RULE_ID = "sdist-files-v1"
EXCLUSIONS = {"PKG-INFO": "Generated by the package build backend."}


class SdistError(Exception):
    pass


class InvestigationError(SdistError):
    pass


class GitError(Exception):
    pass


@dataclass
class Sdist:
    name: str
    url: str
    sha256: str
    size: int
    files: Dict[str, bytes]
    excluded: List[Dict[str, str]]
    archive_path: Optional[str] = None


@dataclass
class CompareCache:
    trees: Dict[str, Dict[str, str]]
    blobs: Dict[str, bytes]

    def __init__(self) -> None:
        self.trees = {}
        self.blobs = {}


@dataclass
class AboutVersionIndex:
    commits: List[str]
    by_version: Dict[str, List[str]]
    unknown: List[str]
    positions: Dict[str, int]

    @classmethod
    def build(cls, commits: Iterable[str], values: Dict[str, Optional[str]]) -> "AboutVersionIndex":
        ordered = list(commits)
        by_version: Dict[str, List[str]] = {}
        unknown: List[str] = []
        for commit in ordered:
            value = values.get(commit)
            if value is None:
                unknown.append(commit)
            else:
                by_version.setdefault(value, []).append(commit)
        return cls(ordered, by_version, unknown, {commit: pos for pos, commit in enumerate(ordered)})

    def candidates(self, version: Optional[str]) -> List[str]:
        if version is None:
            return list(self.commits)
        return sorted(self.unknown + self.by_version.get(version, []), key=self.positions.__getitem__)


def literal_about_version(content: bytes) -> Optional[str]:
    """Return a statically assigned __version__ string without executing code."""
    try:
        module = ast.parse(content.decode("utf-8"))
    except (UnicodeDecodeError, SyntaxError):
        return None
    values = []
    for statement in module.body:
        if isinstance(statement, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__version__"
            for target in statement.targets
        ):
            value = statement.value
        elif isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name) and statement.target.id == "__version__":
            value = statement.value
        else:
            continue
        if not isinstance(value, ast.Constant) or not isinstance(value.value, str):
            return None
        values.append(value.value)
    return values[0] if len(values) == 1 else None


def index_about_versions(
    repo: Path,
    commits: Iterable[str],
    path: str,
    cache: Optional[CompareCache] = None,
    progress: Optional[Callable[[int, int], None]] = None,
) -> Dict[str, Optional[str]]:
    """Read literal __version__ strings for one path across the target history."""
    if cache is None:
        cache = CompareCache()
    result: Dict[str, Optional[str]] = {}
    commit_list = list(commits)
    for position, commit in enumerate(commit_list, start=1):
        tree = cache.trees.get(commit)
        if tree is None:
            tree = _tree(repo, commit)
            cache.trees[commit] = tree
        oid = tree.get(path)
        if oid is None:
            result[commit] = None
            continue
        blob = cache.blobs.get(oid)
        if blob is None:
            process = subprocess.run(
                ["git", "-C", str(repo), "cat-file", "blob", oid],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                check=False,
            )
            if process.returncode:
                raise GitError(process.stderr.decode("utf-8", "replace").strip())
            blob = process.stdout
            cache.blobs[oid] = blob
        result[commit] = literal_about_version(blob)
        if progress is not None and (position % 250 == 0 or position == len(commit_list)):
            progress(position, len(commit_list))
    return result


def _git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo)] + list(args),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode:
        raise GitError(result.stderr.decode("utf-8", "replace").strip())
    return result.stdout.decode("utf-8", "surrogateescape").strip()


def resolve_history(repo: Path, ref: str) -> Tuple[str, List[str], bool]:
    _git(repo, "rev-parse", "--git-dir")
    shallow = _git(repo, "rev-parse", "--is-shallow-repository") == "true"
    resolved = _git(repo, "rev-parse", "--verify", ref + "^{commit}")
    commits = _git(repo, "rev-list", "--first-parent", "--reverse", resolved).splitlines()
    if not commits:
        raise GitError("the selected ref has no commits")
    return resolved, commits, shallow


def read_project_name(repo: Path, commit: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), "show", "{}:pyproject.toml".format(commit)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode:
        raise GitError("pyproject.toml is missing at the selected commit")
    try:
        try:
            import tomllib as toml_parser
        except ImportError:  # pragma: no cover - exercised on CPython 3.10
            import tomli as toml_parser
        project = toml_parser.loads(result.stdout.decode("utf-8")).get("project", {})
    except (UnicodeDecodeError, ValueError) as exc:
        raise GitError("could not parse pyproject.toml: {}".format(exc))
    name = project.get("name") if isinstance(project, dict) else None
    if not isinstance(name, str) or not name.strip():
        raise GitError("pyproject.toml must define a static [project].name")
    return name.strip()


def read_version_path(repo: Path, commit: str) -> Optional[str]:
    """Read a configured, static version-file path without running the build backend."""
    result = subprocess.run(
        ["git", "-C", str(repo), "show", "{}:pyproject.toml".format(commit)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode:
        return None
    try:
        try:
            import tomllib as toml_parser
        except ImportError:  # pragma: no cover - exercised on CPython 3.10
            import tomli as toml_parser
        config = toml_parser.loads(result.stdout.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        return None
    path = config.get("tool", {}).get("hatch", {}).get("version", {}).get("path")
    if not isinstance(path, str) or not path or path.startswith("/") or ".." in Path(path).parts:
        return None
    return path.replace("\\", "/")


def normalize_project_name(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def pypi_index_url(name: str, supplied_url: Optional[str] = None) -> str:
    expected = normalize_project_name(name)
    if supplied_url is None:
        return "https://pypi.org/simple/{}/".format(urllib.parse.quote(expected, safe="-"))
    parsed = urllib.parse.urlsplit(supplied_url)
    if parsed.scheme != "https" or parsed.hostname != "pypi.org" or parsed.query:
        raise SdistError("PyPI URL must be an HTTPS URL on pypi.org")
    parts = [part for part in parsed.path.split("/") if part]
    if len(parts) == 2 and parts[0] == "project":
        project = parts[1]
    elif len(parts) == 2 and parts[0] == "simple":
        project = parts[1]
    else:
        raise SdistError("URL must be a PyPI project page or project Index API URL")
    if normalize_project_name(project) != expected:
        raise SdistError("PyPI URL project does not match pyproject.toml name")
    return "https://pypi.org/simple/{}/".format(urllib.parse.quote(expected, safe="-"))


def pypi_project_files(name: str, supplied_url: Optional[str] = None) -> dict:
    url = pypi_index_url(name, supplied_url)
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/vnd.pypi.simple.v1+json",
            "User-Agent": "sdist2tag/{}".format(__version__),
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            raise SdistError("project is not published on PyPI: {}".format(name))
        raise SdistError("could not read PyPI Index API: HTTP {}".format(exc.code))
    except (urllib.error.URLError, ValueError, OSError) as exc:
        raise SdistError("could not read PyPI Index API: {}".format(exc))
    if normalize_project_name(payload.get("name", "")) != normalize_project_name(name):
        raise SdistError("PyPI Index API returned a different project")
    files = payload.get("files")
    if not isinstance(files, list):
        raise SdistError("invalid PyPI Index API response: missing files")
    versions = payload.get("versions")
    if not isinstance(versions, list):
        versions = []
    return {"url": url, "versions": versions, "files": files}


def sdist_versions(index: dict, project_name: str) -> List[str]:
    found = set()
    normalized = normalize_project_name(project_name)
    prefixes = {normalized, normalized.replace("-", "_")}
    suffixes = (".tar.gz", ".tgz", ".tar.bz2", ".tar.xz", ".zip")
    for item in index["files"]:
        filename = item.get("filename", "")
        if filename.endswith(".whl"):
            wheel_stem = filename[:-4]
            for prefix in prefixes:
                marker = prefix + "-"
                if wheel_stem.lower().startswith(marker):
                    remainder = wheel_stem[len(marker):]
                    version = remainder.split("-", 1)[0]
                    if version:
                        found.add(version)
                    break
            continue
        if not filename.endswith(suffixes):
            continue
        stem = next((filename[: -len(ext)] for ext in suffixes if filename.endswith(ext)), "")
        for prefix in prefixes:
            if stem.lower().startswith(prefix + "-"):
                version = stem[len(prefix) + 1 :]
                if version:
                    found.add(version)
                break
    # Index API versions preserve releases without source files too, so those
    # releases can be reported as missing sdists rather than silently omitted.
    return sorted(set(index["versions"]) | found)


def sdist_file(index: dict, project_name: str, version: str) -> dict:
    normalized = normalize_project_name(project_name)
    prefixes = {normalized, normalized.replace("-", "_")}
    suffixes = (".tar.gz", ".tgz", ".tar.bz2", ".tar.xz", ".zip")
    matches = []
    for item in index["files"]:
        filename = item.get("filename", "")
        if not filename.endswith(suffixes):
            continue
        stem = next((filename[: -len(ext)] for ext in suffixes if filename.endswith(ext)), "")
        if any(stem.lower() == "{}-{}".format(prefix, version).lower() for prefix in prefixes):
            matches.append(item)
    if not matches:
        raise SdistError("PyPI release has no supported source distribution")
    if len(matches) != 1:
        raise SdistError("PyPI release has multiple source distributions")
    item = matches[0]
    digest = item.get("hashes", {}).get("sha256")
    if not digest:
        raise SdistError("PyPI file has no SHA-256 digest")
    return item


def _archive_paths(name: str, is_dir: bool = False) -> List[str]:
    if name.startswith("/") or "\\" in name:
        raise SdistError("unsafe archive path: {}".format(name))
    raw_parts = name.split("/")
    if is_dir and raw_parts[-1] == "":
        raw_parts.pop()
    if not raw_parts or any(part in ("", ".", "..") for part in raw_parts):
        raise SdistError("unsafe archive path: {}".format(name))
    return raw_parts


def _extract_archive(data: bytes, name: str, url: str, expected: str) -> Sdist:
    digest = hashlib.sha256(data).hexdigest()
    if expected and digest.lower() != expected.lower():
        raise SdistError("SHA-256 mismatch: expected {}, got {}".format(expected, digest))
    files: Dict[str, bytes] = {}
    excluded: List[Dict[str, str]] = []
    seen = set()
    top = set()
    if name.endswith(".zip"):
        try:
            archive = zipfile.ZipFile(io.BytesIO(data))
        except (zipfile.BadZipFile, OSError) as exc:
            raise SdistError("invalid zip archive: {}".format(exc))
        with archive:
            for member in archive.infolist():
                parts = _archive_paths(member.filename, member.is_dir())
                normalized = "/".join(parts)
                if normalized in seen:
                    raise SdistError("duplicate archive path: {}".format(normalized))
                seen.add(normalized)
                top.add(parts[0])
                if member.is_dir():
                    continue
                mode = member.external_attr >> 16
                file_type = stat.S_IFMT(mode)
                if stat.S_ISLNK(mode) or file_type not in (0, stat.S_IFREG):
                    raise InvestigationError("special archive member needs investigation: {}".format(member.filename))
                if len(parts) < 2:
                    raise SdistError("archive member is outside the top-level directory: {}".format(member.filename))
                rel = "/".join(parts[1:])
                if rel in EXCLUSIONS:
                    excluded.append({"path": rel, "reason": EXCLUSIONS[rel]})
                    continue
                files[rel] = archive.read(member)
    else:
        try:
            archive = tarfile.open(fileobj=io.BytesIO(data), mode="r:*")
        except (tarfile.TarError, OSError) as exc:
            raise SdistError("invalid tar archive: {}".format(exc))
        with archive:
            for member in archive.getmembers():
                parts = _archive_paths(member.name, member.isdir())
                normalized = "/".join(parts)
                if normalized in seen:
                    raise SdistError("duplicate archive path: {}".format(normalized))
                seen.add(normalized)
                top.add(parts[0])
                if member.isdir():
                    continue
                if not member.isfile():
                    raise InvestigationError("special archive member needs investigation: {}".format(member.name))
                if len(parts) < 2:
                    raise SdistError("archive member is outside the top-level directory: {}".format(member.name))
                rel = "/".join(parts[1:])
                if rel in EXCLUSIONS:
                    excluded.append({"path": rel, "reason": EXCLUSIONS[rel]})
                    continue
                if rel in files:
                    raise SdistError("duplicate source path after stripping root: {}".format(rel))
                stream = archive.extractfile(member)
                if stream is None:
                    raise SdistError("could not read archive member: {}".format(member.name))
                files[rel] = stream.read()
    if len(top) != 1:
        raise SdistError("archive must contain exactly one top-level directory")
    return Sdist(name, url, digest, len(data), files, excluded)


def _fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "sdist2tag/{}".format(__version__)})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.read()
    except (urllib.error.URLError, OSError) as exc:
        raise SdistError("could not download sdist: {}".format(exc))


def _store_archive(data: bytes, filename: str, artifact_dir: Path) -> Path:
    artifact_dir.mkdir(parents=True, exist_ok=True)
    destination = artifact_dir / filename
    if destination.exists():
        if hashlib.sha256(destination.read_bytes()).digest() != hashlib.sha256(data).digest():
            raise SdistError("archive already exists with different content: {}".format(destination))
    else:
        temporary = destination.with_name(destination.name + ".tmp")
        temporary.write_bytes(data)
        temporary.replace(destination)
    return destination


def _get_sdist(index: dict, package: str, version: str, local: Optional[Path], artifact_dir: Path) -> Sdist:
    metadata = sdist_file(index, package, version)
    if local is None:
        data = _fetch(metadata["url"])
    else:
        data = local.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    expected = metadata["hashes"]["sha256"]
    if digest.lower() != expected.lower():
        raise SdistError("SHA-256 mismatch: expected {}, got {}".format(expected, digest))
    archive_path = _store_archive(data, metadata["filename"], artifact_dir)
    result = _extract_archive(data, metadata["filename"], metadata["url"], expected)
    result.archive_path = str(archive_path)
    return result


def _tree(repo: Path, commit: str) -> Dict[str, str]:
    result = subprocess.run(
        ["git", "-C", str(repo), "ls-tree", "-rz", "-r", "--full-tree", commit],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode:
        raise GitError(result.stderr.decode("utf-8", "replace").strip())
    mapping: Dict[str, str] = {}
    for record in result.stdout.split(b"\0"):
        if not record:
            continue
        meta, path = record.split(b"\t", 1)
        mode, kind, oid = meta.split(b" ")
        if kind == b"blob":
            mapping[path.decode("utf-8", "surrogateescape")] = oid.decode("ascii")
    return mapping


def compare(
    repo: Path,
    commits: Iterable[str],
    sdist: Sdist,
    cache: Optional[CompareCache] = None,
    progress: Optional[Callable[[int, int, int, int], None]] = None,
    history_commit_count: Optional[int] = None,
    skipped_by_version: int = 0,
) -> dict:
    if cache is None:
        cache = CompareCache()
    candidates: List[str] = []
    first_mismatch = None
    compared = 0
    commit_list = list(commits)
    total = history_commit_count if history_commit_count is not None else len(commit_list)
    candidate_total = len(commit_list)
    for position, commit in enumerate(commit_list, start=1):
        compared += 1
        tree = cache.trees.get(commit)
        if tree is None:
            tree = _tree(repo, commit)
            cache.trees[commit] = tree
        missing, changed = [], []
        for path, content in sdist.files.items():
            oid = tree.get(path)
            if oid is None:
                missing.append(path)
                continue
            blob = cache.blobs.get(oid)
            if blob is None:
                result = subprocess.run(
                    ["git", "-C", str(repo), "cat-file", "blob", oid],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    check=False,
                )
                if result.returncode:
                    raise GitError(result.stderr.decode("utf-8", "replace").strip())
                blob = result.stdout
                cache.blobs[oid] = blob
            if blob != content:
                changed.append(path)
        if not missing and not changed:
            candidates.append(commit)
            if len(candidates) == 1:
                selected = commit
        elif first_mismatch is None:
            first_mismatch = {"commit": commit, "missing_paths": missing[:10], "changed_paths": changed[:10]}
        if progress is not None and (position % 250 == 0 or position == candidate_total):
            progress(position, candidate_total, compared, skipped_by_version)
    status = "match" if candidates else "mismatch"
    return {
        "status": status,
        "selected_commit": candidates[0] if candidates else None,
        "matching_commits": candidates,
        "comparison": {
            "rule": RULE_ID,
            "files": len(sdist.files),
            "files_compared_per_commit": len(sdist.files),
            "commits_considered": total,
            "commits_compared": compared,
            "commits_skipped_by_about_version": skipped_by_version,
            "excluded": sdist.excluded,
            "repository_only_files_compared": False,
            "note": "Files absent from the sdist were not compared.",
            "first_mismatch_examples": first_mismatch,
        },
    }


def create_tags(repo: Path, results: List[dict], package: str, report_path: str, prefix: str) -> None:
    planned = []
    seen_tags = set()
    for result in results:
        if result.get("status") != "match":
            continue
        version = result["version"]
        tag = prefix + version
        if tag in seen_tags:
            raise GitError("duplicate target tag in report: {}".format(tag))
        seen_tags.add(tag)
        if subprocess.run(
            ["git", "-C", str(repo), "check-ref-format", "refs/tags/{}".format(tag)],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False
        ).returncode:
            raise GitError("invalid tag name: {}".format(tag))
        exists = subprocess.run(
            ["git", "-C", str(repo), "show-ref", "--verify", "--quiet", "refs/tags/{}".format(tag)],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False
        ).returncode == 0
        if exists:
            resolved = subprocess.run(
                ["git", "-C", str(repo), "rev-parse", "--verify", "refs/tags/{}^{{}}".format(tag)],
                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=False
            )
            current = resolved.stdout.decode("ascii", "replace").strip() if resolved.returncode == 0 else "unresolvable"
            if current == result["selected_commit"]:
                result["tag"] = {"name": tag, "status": "existing_same_commit", "commit": current}
            else:
                result["tag"] = {"name": tag, "status": "conflict", "commit": current}
                raise GitError("tag conflict for {}: expected {}, existing tag points to {}".format(
                    tag, result["selected_commit"], current
                ))
        else:
            planned.append((tag, result))
    for tag, result in planned:
        sdist = result["sdist"]
        message = (
            "PyPI release {} source snapshot\n\n"
            "sdist: {}\nsha256: {}\n"
            "Selection: first content match on the target ref's first-parent history.\n"
            "This does not prove the actual build source commit.\n"
            "Excluded generated metadata: {}\nReport: {}\n"
        ).format(result["version"], sdist["name"], sdist["sha256"], ", ".join(x["path"] for x in sdist["excluded"]) or "none", report_path)
        subprocess.run(["git", "-C", str(repo), "tag", "-a", tag, result["selected_commit"], "-m", message], check=True)
        result["tag"] = {"name": tag, "status": "created", "commit": result["selected_commit"]}

